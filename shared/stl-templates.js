export function wireAppShellTsx(title, domain, componentPaths = []) {
  const imports = componentPaths
    .map((path) => {
      const name = pathToComponentName(path);
      const rel = path.replace(/^src\//, './').replace(/\.tsx$/, '');
      return `import { ${name} } from '${rel}';`;
    })
    .join('\n');

  const panels = componentPaths
    .map((path) => {
      const name = pathToComponentName(path);
      return `        <${name} />`;
    })
    .join('\n');

  return `import React from 'react';
${imports ? `${imports}\n` : ''}
/** App shell — ${title} */
export function AppShell() {
  return (
    <div className="app-root" data-domain="${domain}">
      <header><h1>${title}</h1></header>
      <main className="app-layout">
${panels || '        <p>Generated by EndDesign Ingestor</p>'}
      </main>
    </div>
  );
}
`;
}

function pathToComponentName(path) {
  const base = path.split('/').pop().replace(/\.[^.]+$/, '');
  return base
    .split('_')
    .map((p) => p.charAt(0).toUpperCase() + p.slice(1))
    .join('');
}

